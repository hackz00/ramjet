function nodeExternals(
	{ context, request }: ExternalItemFunctionData,
	callback: (
		err?: Error,
		result?: ExternalItemValue,
		type?: ExternalsType,
	) => void,
) {
	if (!/^(\.|\/|[A-Za-z]:[\\/])/.test(request || "")) {
		return callback(undefined, request);
	}

	callback();
}

function extractRuntimeExportNames(source: string): string[] {
	const names = new Set<string>();

	const esmMatches = source.matchAll(/export\s*\{([^}]+)\}\s*;/g);
	for (const m of esmMatches) {
		for (const part of m[1].split(",")) {
			const trimmed = part.trim();
			if (!trimmed) continue;
			const asMatch = trimmed.match(/\s+as\s+([A-Za-z_$][\w$]*)\s*$/);
			const name = asMatch
				? asMatch[1]
				: trimmed.match(/^([A-Za-z_$][\w$]*)/)?.[1];
			if (name) names.add(name);
		}
	}
	if (names.size > 0) return [...names];

	const defMatches = [
		...source.matchAll(
			/\b[A-Za-z_$][\w$]*\.d\([A-Za-z_$][\w$]*,\s*\{([\s\S]*?)\}\)/g,
		),
	];
	if (defMatches.length > 0) {
		const last = defMatches[defMatches.length - 1][1];
		for (const m of last.matchAll(/([A-Za-z_$][\w$]*)\s*:/g)) {
			names.add(m[1]);
		}
	}
	return [...names];
}

function renderExternalStub(names: string[], globalName: string): string {
	const sorted = [...names].sort();
	return [
		"// generated by ExternalStubPlugin",
		`// exports from globalThis.${globalName} (set by the IIFE bundle).`,
		`const __external = /** @type {any} */ (globalThis).${globalName};`,
		"export const {",
		...sorted.map((n) => `\t${n},`),
		"} = __external;",
		"",
	].join("\n");
}

class ExternalStubPlugin {
	bundleFilename: string;
	stubFilename: string;
	globalName: string;
	outputDir: string;

	constructor(opts: {
		bundleFilename: string;
		stubFilename: string;
		globalName: string;
		outputDir: string;
	}) {
		this.bundleFilename = opts.bundleFilename;
		this.stubFilename = opts.stubFilename;
		this.globalName = opts.globalName;
		this.outputDir = opts.outputDir;
	}

	apply(compiler: WebpackCompiler) {
		compiler.hooks.afterEmit.tap("ExternalStubPlugin", () => {
			const bundlePath = join(this.outputDir, this.bundleFilename);
			const stubPath = join(this.outputDir, this.stubFilename);
			let source: string;
			try {
				source = readFileSync(bundlePath, "utf-8");
			} catch (e: any) {
				console.error(
					`ExternalStubPlugin: cannot read ${bundlePath}: ${e.message}`,
				);
				return;
			}

			const names = extractRuntimeExportNames(source);
			if (names.length === 0) {
				console.warn(
					`ExternalStubPlugin: no exports discovered in ${bundlePath}; stub not written`,
				);
				return;
			}

			const stub = renderExternalStub(names, this.globalName);
			writeFileSync(stubPath, stub);
			console.log(
				`ExternalStubPlugin: wrote ${this.stubFilename} (${names.length} exports → globalThis.${this.globalName})`,
			);
		});
	}
}

class TypeScriptDeclarationsPlugin {
	dir: string;
	tsconfigName: string;
	useAlias: boolean;
	tempDir: string;

	constructor(
		dir: string,
		tempDir: string,
		tsconfigName: string = "tsconfig.types.json",
		useAlias: boolean = true,
	) {
		this.dir = dir;
		this.tempDir = tempDir;
		this.tsconfigName = tsconfigName;
		this.useAlias = useAlias;
	}

	apply(compiler: WebpackCompiler) {
		compiler.hooks.afterEmit.tapPromise(
			"TypeScriptDeclarationsPlugin",
			async () => {
				const { stdout } = await execAsync(
					`pnpm exec tsc --project ${this.tsconfigName}`,
					{ cwd: this.dir },
				);
				if (stdout) console.log(stdout);
				if (this.useAlias) {
					await execAsync(
						`pnpm exec tsc-alias --project ${this.tsconfigName}`,
						{ cwd: this.dir },
					);
				}
				if (this.dir === controllerdir) {
					await execAsync(
						"pnpm exec tsc ../rpc/index.ts --declaration --emitDeclarationOnly --skipLibCheck --target ES2022 --module ESNext --moduleResolution bundler --outDir dist/types/rpc",
						{ cwd: this.dir },
					);
					const entry = join(this.dir, "dist/types/index.d.ts");
					writeFileSync(
						entry,
						readFileSync(entry, "utf8").replaceAll(
							'"@ramjet/rpc"',
							'"./rpc/index"',
						),
					);
				}
				if (this.dir === controllerdir) {
					copyFileSync(
						join(this.dir, "src/types.d.ts"),
						join(this.dir, "dist/types/types.d.ts"),
					);
				}
				if (this.dir === ramjetdir) {
					const wasmTypes = join(this.dir, "dist/types/rewriter/wasm/out");
					mkdirSync(wasmTypes, { recursive: true });
					copyFileSync(
						join(this.dir, "rewriter/wasm/out/wasm.d.ts"),
						join(wasmTypes, "wasm.d.ts"),
					);
					const wrapper = join(
						this.dir,
						"dist/types/shared/rewriters/wasm.d.ts",
					);
					writeFileSync(
						wrapper,
						readFileSync(wrapper, "utf8").replaceAll(
							"../../../rewriter/wasm/out/wasm.js",
							"../../rewriter/wasm/out/wasm",
						),
					);
				}
				const globalTypes = join(this.dir, "src/global.d.ts");
				if (existsSync(globalTypes)) {
					mkdirSync(join(this.dir, "dist/types"), { recursive: true });
					copyFileSync(globalTypes, join(this.dir, "dist/types/global.d.ts"));
				}
				const temporary = resolve(this.dir, this.tempDir);
				if (
					!temporary.startsWith(resolve(this.dir) + "/") &&
					!temporary.startsWith(resolve(this.dir) + "\\")
				) {
					throw new Error("Declaration cleanup must stay inside the package.");
				}
				rmSync(temporary, { recursive: true, force: true });
			},
		);
	}
}

